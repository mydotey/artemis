-- SQLite database schema for testing

-- instance table
CREATE TABLE IF NOT EXISTS instance (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  INSTANCE_ID TEXT NOT NULL,
  SERVICE_ID TEXT NOT NULL,
  REGION_ID TEXT NOT NULL,
  OPERATION TEXT NOT NULL,
  OPERATOR_ID TEXT NOT NULL,
  TOKEN TEXT NOT NULL,
  CREATE_TIME DATETIME DEFAULT CURRENT_TIMESTAMP,
  DataChange_LastTime DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_instance ON instance(INSTANCE_ID, SERVICE_ID, REGION_ID, OPERATION);

-- instance_log table
CREATE TABLE IF NOT EXISTS instance_log (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  INSTANCE_ID TEXT NOT NULL,
  SERVICE_ID TEXT NOT NULL,
  REGION_ID TEXT NOT NULL,
  OPERATION TEXT NOT NULL,
  OPERATOR_ID TEXT NOT NULL,
  TOKEN TEXT NOT NULL,
  COMPLETE INTEGER DEFAULT 0,
  EXTENSIONS TEXT DEFAULT '{}',
  CREATE_TIME DATETIME DEFAULT CURRENT_TIMESTAMP,
  DataChange_LastTime DATETIME DEFAULT CURRENT_TIMESTAMP
);

